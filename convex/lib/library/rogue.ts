// The rogue: five levels, two archetypes, and one line of damage that matters more
// than everything else on the sheet put together.
//
// Content only — the shape is in ./types.ts. Every sheet is written out in full
// rather than spread from the level below it, so that a player comparing level 3 to
// level 4 can read both without holding one of them in their head.
//
// Three choices worth knowing about before editing this file:
//
// - **Level 3 is an ability score improvement rather than a feat.** Dexterity is the
//   rogue's attack, its damage, its Armour Class, its initiative and four of its
//   seven skills, so +2 to it moves more numbers at once than any feat a beginner
//   should be handed. A feat here would also be a rule to remember on a sheet whose
//   whole appeal is that there is only one.
// - **Uncanny Dodge is brought forward from level 5 to level 4.** Every other class
//   gets Extra Attack at level 5 and the rogue famously does not; leaving the gap
//   where 5e puts it would mean a level 4 in which nothing happened but a bigger
//   die. Sneak Attack steps up at the same level, so 4 is the spike.
// - **Evasion is brought forward from level 7 to level 5**, for the same reason from
//   the other end: level 5 needs to be worth reaching.
//
// Cunning Action's Dash, Disengage and Hide are described as what they let a rogue
// do, never in terms of speed or of movement-impairing conditions — both are outside
// the D&D Lite subset (docs/requirements.md), and Second-Storey Work is the entry
// where they would otherwise creep back in.

